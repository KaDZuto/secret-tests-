def react(world, text):
    """An answer to a line the player typed, in the chapter's own words."""
    lowered = " ".join(str(text or "").lower().split())
    for keys, lines in _REACTIONS:
        if any(key in lowered for key in keys):
            steps = [dict(x) for x in lines]
            break
    else:
        steps = [dict(x) for x in _DEFAULT_REACTION]
    for step in steps:
        if not step.get("background"):
            step["background"] = GATE
    return steps
