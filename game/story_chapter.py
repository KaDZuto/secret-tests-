def s(text, who=None, emotion=NEUTRAL, bg=None, position="center", pose=P0,
      music=None, choices=None, kind=None, when=None, note=None, state=None):
    """One step, in exactly the shape `script.rpy` and `engine.py` already read.

    `when` names a world flag the step needs to be shown at all, `note` names a flag it sets on
    the way past, and `state` is a `state_patch` the engine applies when the step is consumed.
    """
    step = {
        "type": kind or ("choice" if choices else ("dialogue" if who else "narration")),
        "speaker": who,
        "who": who,
        "text": text,
    }
    if bg:
        step["background"] = bg
    if who:
        step["characters"] = [{"id": who, "position": position, "emotion": emotion, "pose": pose}]
    if music:
        step["music_intent"] = music
    if choices:
        step["choices"] = choices
        step["checkpoint"] = True
    if when:
        step["when"] = when
    if note:
        step["note"] = note
    if state:
        step["state_patch"] = state
    return step


def opt(ident, text, flag=None, goto=None):
    """One answer. `flag` is what the world remembers, `goto` is the block it opens."""
    return {"id": ident, "text": text, "world_flag": flag or ("ch1_" + ident), "goto": goto}


def scene(bg, emotion=NEUTRAL, pose=P0, position="center"):
    """A step that only changes the place and the face on it."""
    return {"type": "scene", "background": bg,
            "characters": [{"id": ASUNA, "position": position, "emotion": emotion, "pose": pose}]}


