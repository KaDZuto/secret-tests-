def _wanted(step, world):
    """Whether this step belongs in this playthrough."""
    need = step.get("when")
    if not need:
        return True
    flags = world.get("flags") or {}
    return bool(flags.get(need))


def _chosen_goto(world, options):
    """Which branch the player took out of the choice we just showed."""
    ids = set(options or [])
    for entry in reversed(world.get("player_choices") or []):
        if entry.get("id") in ids:
            return entry.get("goto")
    return None


def _answered(world, options):
    """True when the player has already answered the question that is pending."""
    ids = set(options or {})
    for entry in reversed(world.get("player_choices") or []):
        if entry.get("id") in ids:
            return True
    return False


def _advance(world, cursor, steps):
    """Pick the next block after the one that just ran out."""
    options = cursor.get("options") or {}
    chosen = _chosen_goto(world, options)
    cursor["options"] = {}
    if chosen and chosen in BLOCKS:
        cursor["block"] = chosen
        cursor["index"] = 0
        return True
    block = BLOCKS.get(cursor.get("block")) or {}
    nxt = block.get("next")
    if nxt and nxt in BLOCKS:
        cursor["block"] = nxt
        cursor["index"] = 0
        return True
    return False


def next_steps(world, want=2):
    """The next `want` steps of the chapter, in the shape the engine already plays.

    Stops at a choice: a choice is a question to the player, and the block that answers it
    must not be queued before the answer is known.
    """
    want = max(1, int(want or 1))
    cursor = world.get("chapter") or new_cursor()
    world["chapter"] = cursor
    if cursor.get("done"):
        return []

    out = []
    guard = 0
    while len(out) < want and guard < 200:
        guard += 1
        block = BLOCKS.get(cursor.get("block"))
        if not block:
            break
        index = int(cursor.get("index", 0))
        if index >= len(block["steps"]):
            if cursor.get("options") and not _answered(world, cursor["options"]):
                # The block ended on a choice and the player has not answered yet. Advancing now
                # would send the scene down the default branch before the decision was made, so
                # the chapter simply waits here.
                break
            # The flag-dependent beats hang off the block that just ended, so a playthrough
            # reads differently without the whole scene being written twice.
            for flag, extra in FLAG_BEATS.items():
                if (world.get("flags") or {}).get(flag) and flag not in cursor["seen"]:
                    cursor["seen"].append(flag)
                    out.extend([x for x in extra if _wanted(x, world)])
                    if len(out) >= want:
                        break
            if len(out) >= want:
                break
            if not _advance(world, cursor, block):
                cursor["done"] = True
                break
            continue

        step = block["steps"][index]
        cursor["index"] = index + 1
        if not _wanted(step, world):
            continue
        if step.get("note"):
            world.setdefault("flags", {})[step["note"]] = True
        if step.get("choices"):
            options = {c.get("id"): c.get("goto") for c in step["choices"]}
            cursor["options"] = options
            cursor["saw_choice"] = step["choices"][0].get("id")
        # `script.rpy` shows a `choice` step by opening the choice screen and never says its
        # text, so a question that was written with a line before it is played as two steps:
        # the line, then the question.
        if step.get("choices") and step.get("text"):
            line = dict(step)
            line.pop("choices", None)
            line.pop("checkpoint", None)
            line["type"] = "dialogue" if line.get("speaker") else "narration"
            question = dict(step)
            question["text"] = ""
            out.append(line)
            out.append(question)
        else:
            out.append(step)
        if step.get("choices"):
            break

    if not out and cursor.get("done"):
        return []
    if out and out[-1].get("choices"):
        cursor["waiting_for_answer"] = True
    return out


def waiting_for_answer(world):
    """True while a choice is on screen and the block behind it has not been left yet."""
    cursor = world.get("chapter") or {}
    return bool(cursor.get("options")) and not _answered(world, cursor["options"])


def chapter_finished(world):
    """True when the chapter has run out of blocks and the end card is due."""
    cursor = world.get("chapter") or {}
    return bool(cursor.get("done"))


